const DICTS: Record<Lang, Dict> = { en, ms, zh };
export const LANG_LABELS: Record<Lang, string> = { en: 'EN', ms: 'BM', zh: '中文' };

type T = (key: MessageKey, vars?: Record<string, string | number>) => string;
interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: T;
}

const Ctx = createContext<I18n | null>(null);
const STORAGE_KEY = 'homeset.lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'ms' || saved === 'zh') return saved;
  } catch {
    /* storage unavailable */
  }
  const nav = navigator.language.toLowerCase();
  return nav.startsWith('zh') ? 'zh' : nav.startsWith('ms') ? 'ms' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* storage unavailable */
    }
    document.documentElement.lang = l;
  }, []);
  const t = useCallback<T>(
    (key, vars) => {
      let s: string = DICTS[lang][key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error('useI18n outside I18nProvider');
  return ctx;
}

export function LangSwitcher() {
  const { lang, setLang } = useI18n();
  return (
    <div className="seg seg-sm" role="group" aria-label="Language">
      {(Object.keys(LANG_LABELS) as Lang[]).map((l) => (
        <button key={l} className={l === lang ? 'on' : ''} onClick={() => setLang(l)}>
          {LANG_LABELS[l]}
        </button>
      ))}
    </div>
  );
}
